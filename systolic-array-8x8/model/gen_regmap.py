#!/usr/bin/env python3
"""Generate plain SV, Python, and C register constants from regmap.json."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(__file__).with_name("regmap.json")
OUTPUTS = {
    ROOT / "tb" / "accel_regs_pkg.sv": "sv",
    ROOT / "sw" / "common" / "accel_regs.py": "py",
    ROOT / "sw" / "common" / "accel_regs.h": "h",
}


def bits(text: str) -> tuple[int, int]:
    parts = [int(x) for x in text.split(":")]
    msb, lsb = (parts[0], parts[-1])
    if not (0 <= lsb <= msb < 32):
        raise ValueError(f"invalid bit range {text}")
    return lsb, msb - lsb + 1


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    seen = set()
    for reg in data["registers"]:
        off = int(reg["offset"], 0)
        if off % 4 or off in seen:
            raise ValueError(f"duplicate or unaligned offset {reg['offset']}")
        seen.add(off)
        for field in reg["fields"]:
            bits(field["bits"])
    return data


def constants(data: dict):
    for reg in data["registers"]:
        yield reg["name"], int(reg["offset"], 0), "offset"
        for field in reg["fields"]:
            lsb, width = bits(field["bits"])
            base = f"{reg['name']}_{field['name']}"
            yield f"{base}_LSB", lsb, "field"
            yield f"{base}_WIDTH", width, "field"


def render(data: dict, kind: str) -> str:
    rows = list(constants(data))
    banner = "Generated by model/gen_regmap.py from model/regmap.json; do not edit."
    if kind == "py":
        out = [f'"""{banner}"""', f"REGMAP_VERSION = {data['version']}", ""]
        out += [f"{name} = 0x{value:03X}" if typ == "offset" else f"{name} = {value}"
                for name, value, typ in rows]
        return "\n".join(out) + "\n"
    if kind == "h":
        out = [f"/* {banner} */", "#ifndef ACCEL_REGS_H", "#define ACCEL_REGS_H", "",
               f"#define ACCEL_REGMAP_VERSION {data['version']}u"]
        out += [f"#define ACCEL_{name} 0x{value:03X}u" if typ == "offset"
                else f"#define ACCEL_{name} {value}u" for name, value, typ in rows]
        out += ["", "#endif /* ACCEL_REGS_H */", ""]
        return "\n".join(out)
    out = [f"// {banner}", "package accel_regs_pkg;",
           f"  localparam int unsigned REGMAP_VERSION = {data['version']};"]
    out += [f"  localparam logic [11:0] {name} = 12'h{value:03X};" if typ == "offset"
            else f"  localparam int unsigned {name} = {value};" for name, value, typ in rows]
    out += ["endpackage", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load()
    stale = []
    for path, kind in OUTPUTS.items():
        wanted = render(data, kind)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != wanted:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted, encoding="utf-8", newline="\n")
    if stale:
        print("STALE regmap outputs: " + ", ".join(map(str, stale)))
        return 1
    print("PASS gen_regmap check" if args.check else "PASS gen_regmap generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
